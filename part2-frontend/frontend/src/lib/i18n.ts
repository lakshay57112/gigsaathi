/** Look up interface text. Falls back to English when a translation is missing. */
export function translate(language: string, key: TextKey): string {
  if (language === "hi") return hi[key] ?? en[key];
  return en[key];
}

export function isTranslated(language: string): boolean {
  return language === "en" || language === "hi";
}

